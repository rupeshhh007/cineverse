'use client';

import React, { useState, useEffect } from 'react';
import Link from 'next/link';
import { Database, X, Copy, Check, ArrowUpRight, Terminal } from 'lucide-react';
import { usePathname } from 'next/navigation';

export default function DbmsInspectorDrawer() {
  const [isOpen, setIsOpen] = useState(false);
  const [copied, setCopied] = useState(false);
  const pathname = usePathname();

  const [currentQueryMeta, setCurrentQueryMeta] = useState<{
    pageName: string;
    subtext: string;
    badge: string;
    sql: string;
    concepts: string[];
    explanation: string;
  }>({
    pageName: 'Discover / Trending films',
    subtext: 'Illustrative query pattern, not a measured execution trace.',
    badge: 'EXAMPLE SQL',
    sql: `SELECT m.title, m.avg_rating,
       v.bayesian_score
FROM movies m
LEFT JOIN v_trending_movies v
  ON v.movie_id = m.movie_id
ORDER BY v.bayesian_score DESC;`,
    concepts: ['JOIN', 'AGGREGATION', 'VIEW'],
    explanation: 'The view ranks films using weighted community ratings. A join links it to the movie catalog.'
  });

  useEffect(() => {
    if (pathname === '/') {
      setCurrentQueryMeta({
        pageName: 'Discover / Trending films',
        subtext: 'Illustrative query pattern, not a measured execution trace.',
        badge: 'EXAMPLE SQL',
        sql: `SELECT m.title, m.avg_rating,
       v.bayesian_score
FROM movies m
LEFT JOIN v_trending_movies v
  ON v.movie_id = m.movie_id
ORDER BY v.bayesian_score DESC;`,
        concepts: ['JOIN', 'AGGREGATION', 'VIEW'],
        explanation: 'The view ranks films using weighted community ratings. A join links it to the movie catalog.'
      });
    } else if (pathname?.startsWith('/movies/')) {
      setCurrentQueryMeta({
        pageName: 'Film Details & Reviews',
        subtext: '3-way join aggregate with real-time cached rating averages.',
        badge: 'EXAMPLE SQL',
        sql: `SELECT m.*, 
       json_agg(DISTINCT p.*) AS cast,
       json_agg(r.*) AS reviews
FROM movies m
LEFT JOIN movie_cast mc ON m.movie_id = mc.movie_id
LEFT JOIN people p ON mc.person_id = p.person_id
LEFT JOIN reviews r ON m.movie_id = r.movie_id
WHERE m.movie_id = $1
GROUP BY m.movie_id;`,
        concepts: ['3-WAY JOIN', 'JSON_AGG', 'TRIGGER SYNC'],
        explanation: 'Aggregates movie credits and member critiques in a single normalized query with trigger-synced rating averages.'
      });
    } else if (pathname === '/feed') {
      setCurrentQueryMeta({
        pageName: 'Social Activity Feed',
        subtext: 'Event-driven timeline generated by PostgreSQL audit triggers.',
        badge: 'EXAMPLE SQL',
        sql: `SELECT al.*, u.username, u.avatar_url,
       m.title, m.poster_url
FROM activity_logs al
JOIN users u ON al.user_id = u.user_id
LEFT JOIN movies m ON al.target_id = m.movie_id
ORDER BY al.created_at DESC LIMIT 30;`,
        concepts: ['AUDIT LOG', 'TRIGGERS', 'EVENT SOURCING'],
        explanation: 'Entries are automatically logged by trg_log_review_activity and trg_log_watchlist_add triggers.'
      });
    } else if (pathname === '/community') {
      setCurrentQueryMeta({
        pageName: 'Community Leaderboard',
        subtext: 'SQL window function ranking cinephiles by reviews and helpful votes.',
        badge: 'EXAMPLE SQL',
        sql: `SELECT u.user_id, u.username,
       COUNT(r.review_id) AS total_reviews,
       SUM(r.likes_count) AS total_likes,
       DENSE_RANK() OVER (
         ORDER BY COUNT(r.review_id) DESC,
                  SUM(r.likes_count) DESC
       ) AS rank
FROM users u
LEFT JOIN reviews r ON u.user_id = r.user_id
GROUP BY u.user_id;`,
        concepts: ['DENSE_RANK()', 'WINDOW FUNCTION', 'GROUP BY'],
        explanation: 'Evaluates community ranking using DENSE_RANK() over aggregate review and like counts.'
      });
    } else if (pathname === '/lists' || pathname?.startsWith('/lists/')) {
      setCurrentQueryMeta({
        pageName: 'Curated Collections',
        subtext: 'Relational parent-child collection schema with cascade integrity.',
        badge: 'EXAMPLE SQL',
        sql: `SELECT w.*, u.username, 
       COUNT(wi.movie_id) AS movie_count
FROM watchlists w
JOIN users u ON w.user_id = u.user_id
LEFT JOIN watchlist_items wi 
  ON w.watchlist_id = wi.watchlist_id
WHERE w.is_public = TRUE
GROUP BY w.watchlist_id, u.user_id;`,
        concepts: ['COMPOSITE KEY', 'CASCADE DELETE', 'OUTER JOIN'],
        explanation: 'Queries curated watchlists joined with watchlist_items to render dynamic stacked film covers.'
      });
    } else if (pathname?.startsWith('/profile/')) {
      setCurrentQueryMeta({
        pageName: 'Member Profile & Analytics',
        subtext: 'PL/pgSQL analytical function computing member rating spread.',
        badge: 'EXAMPLE SQL',
        sql: `SELECT fn_get_user_analytics($1) AS analytics;
-- Generates favorite genres and 10-point histogram.

SELECT * FROM fn_recommend_movies($1, 5);
-- Generates collaborative recommendations.`,
        concepts: ['STORED PROCEDURE', 'PL/pgSQL', 'HISTOGRAM'],
        explanation: 'Calls database-side procedural functions fn_get_user_analytics and fn_recommend_movies.'
      });
    } else if (pathname === '/dbms-console') {
      setCurrentQueryMeta({
        pageName: 'The Projection Room',
        subtext: 'Direct interactive PostgreSQL 16 terminal and schema introspection.',
        badge: 'LIVE TERMINAL',
        sql: `SELECT table_name, table_type 
FROM information_schema.tables 
WHERE table_schema = 'public';`,
        concepts: ['CATALOG INTROSPECTION', 'TRANSACTIONS', '3NF SCHEMA'],
        explanation: 'Runs live parameterized queries against the active relational PostgreSQL engine.'
      });
    }
  }, [pathname]);

  const handleCopy = () => {
    navigator.clipboard.writeText(currentQueryMeta.sql);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <>
      {/* Floating Pill Trigger */}
      <div className="fixed bottom-6 right-6 z-40">
        <button
          type="button"
          onClick={() => setIsOpen(true)}
          className="flex items-center gap-2 px-4 py-2.5 rounded-full bg-[#1d251b] hover:bg-[#273224] text-[#efece3] text-xs font-semibold border border-[#3e4c3a] shadow-2xl transition-all group"
        >
          <Database className="w-3.5 h-3.5 text-[#a9cc92]" />
          <span>DBMS INSPECTOR</span>
          <ArrowUpRight className="w-3.5 h-3.5 text-[#aeb9a8] group-hover:text-[#efece3] transition-colors" />
        </button>
      </div>

      {/* Slide-over Drawer Overlay */}
      {isOpen && (
        <div className="fixed inset-0 z-50 flex justify-end bg-black/75 backdrop-blur-md animate-fade-in">
          <div 
            className="w-full max-w-xl bg-[#161d15] border-l border-[#354332] h-full overflow-y-auto p-6 sm:p-8 flex flex-col justify-between shadow-2xl text-[#efece3]"
            onClick={(e) => e.stopPropagation()}
          >
            <div className="space-y-6">
              {/* Header */}
              <div className="flex items-start justify-between pb-5 border-b border-[#293527]">
                <div>
                  <div className="text-[10px] font-mono text-[#8d9c87] uppercase tracking-widest font-semibold">
                    Cineverse / Under the surface
                  </div>
                  <h2 className="text-2xl font-bold text-[#efece3] mt-1 font-serif">
                    The Query Lens
                  </h2>
                  <p className="text-xs text-[#aeb9a8] mt-1">
                    Understand the SQL powering this view.
                  </p>
                </div>
                <button
                  type="button"
                  onClick={() => setIsOpen(false)}
                  className="p-2 rounded-xl bg-[#1f281d] border border-[#3a4836] text-[#aeb9a8] hover:text-[#efece3] hover:bg-[#283526] transition-colors"
                  aria-label="Close drawer"
                >
                  <X className="w-4 h-4" />
                </button>
              </div>

              {/* Current Screen Card */}
              <div className="p-4 rounded-2xl bg-[#1d261c] border border-[#374633] space-y-1">
                <div className="flex items-center justify-between">
                  <span className="text-[10px] font-mono uppercase tracking-wider text-[#798873] font-semibold">
                    Current Screen
                  </span>
                  <span className="text-[10px] font-mono px-2 py-0.5 rounded bg-[#151c14] border border-[#3e4c3a] text-[#a9cc92] font-semibold">
                    {currentQueryMeta.badge}
                  </span>
                </div>
                <h3 className="text-sm font-semibold text-[#efece3]">
                  {currentQueryMeta.pageName}
                </h3>
                <p className="text-xs text-[#aeb9a8]">
                  {currentQueryMeta.subtext}
                </p>
              </div>

              {/* Relational Concepts */}
              <div className="space-y-2">
                <div className="text-[10px] font-mono uppercase tracking-widest text-[#798873] font-semibold">
                  Relational Concepts
                </div>
                <div className="flex flex-wrap gap-2">
                  {currentQueryMeta.concepts.map((concept, i) => (
                    <span
                      key={i}
                      className="px-3 py-1 rounded-full bg-[#1e271d] border border-[#384835] text-[11px] font-mono font-medium text-[#c0ceba]"
                    >
                      {concept}
                    </span>
                  ))}
                </div>
              </div>

              {/* Query Deconstruction */}
              <div className="space-y-2">
                <div className="flex items-center justify-between">
                  <div className="text-[10px] font-mono uppercase tracking-widest text-[#798873] font-semibold">
                    Query Deconstruction
                  </div>
                  <button
                    type="button"
                    onClick={handleCopy}
                    className="flex items-center gap-1.5 text-xs text-[#aeb9a8] hover:text-[#efece3] transition-colors"
                  >
                    {copied ? <Check className="w-3.5 h-3.5 text-[#a9cc92]" /> : <Copy className="w-3.5 h-3.5" />}
                    <span>{copied ? 'Copied' : 'Copy'}</span>
                  </button>
                </div>
                <div className="rounded-2xl bg-[#121811] border border-[#303d2c] p-4 font-mono text-xs text-[#d8e2d4] overflow-x-auto leading-relaxed">
                  <pre className="whitespace-pre-wrap">{currentQueryMeta.sql}</pre>
                </div>
              </div>

              {/* What This Does */}
              <div className="p-4 rounded-2xl bg-[#1d261c] border border-[#374633] space-y-1">
                <div className="text-[10px] font-mono uppercase tracking-wider text-[#798873] font-semibold">
                  What This Does
                </div>
                <p className="text-xs text-[#aeb9a8] leading-relaxed">
                  {currentQueryMeta.explanation}
                </p>
              </div>
            </div>

            {/* Footer Action */}
            <div className="pt-6 border-t border-[#293527] mt-6">
              <Link
                href="/dbms-console"
                onClick={() => setIsOpen(false)}
                className="w-full py-3.5 rounded-xl bg-[#a9cc92] hover:bg-[#b8dca2] text-[#152016] text-xs font-bold flex items-center justify-center gap-2 transition-colors shadow-lg"
              >
                <span>Open the full Projection Room</span>
                <ArrowUpRight className="w-4 h-4" />
              </Link>
            </div>
          </div>
        </div>
      )}
    </>
  );
}
